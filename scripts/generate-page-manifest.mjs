#!/usr/bin/env node
// Builds app/_components/generated/page-manifest.tsx — a static slug →
// component map used by route files to look up the body component for a
// given slug without hard-coded imports. Run this after re-running the
// HTML→JSX converter for new pages.

import fs from 'node:fs';
import path from 'node:path';

const GEN_DIR = path.join('app', '_components', 'generated');

function slugToComponentName(slug) {
  return slug.split(/[-_]/).map((p) => p[0].toUpperCase() + p.slice(1)).join('') + 'Body';
}

const slugs = fs
  .readdirSync(path.join('app', '_html'))
  .filter((f) => f.endsWith('.body.html'))
  .map((f) => f.replace(/\.body\.html$/, ''))
  .sort();

const imports = slugs
  .map((slug) => `import ${slugToComponentName(slug)} from './${slugToComponentName(slug)}';`)
  .join('\n');

const mapEntries = slugs
  .map((slug) => `  '${slug}': ${slugToComponentName(slug)},`)
  .join('\n');

const file = `// AUTO-GENERATED by scripts/generate-page-manifest.mjs. Re-run after the
// HTML→JSX converter to keep the slug → component map in sync.
/* eslint-disable */
import type { ComponentType } from 'react';

${imports}

export const pageManifest: Record<string, ComponentType> = {
${mapEntries}
};

export type PageSlug = keyof typeof pageManifest;
`;

fs.writeFileSync(path.join(GEN_DIR, 'page-manifest.tsx'), file, 'utf8');
console.log(`wrote ${slugs.length} entries to ${path.join(GEN_DIR, 'page-manifest.tsx')}`);
